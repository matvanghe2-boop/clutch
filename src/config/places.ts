const clean = (s: string) =>
  s
    .toLowerCase()
    // Lettres que la décomposition n'allège pas : Łódź, Øresund, Ærø, Straße.
    .replace(/ł/g, "l")
    .replace(/ø/g, "o")
    .replace(/æ/g, "ae")
    .replace(/ß/g, "ss")
    .normalize("NFD")
    .replace(/\p{M}/gu, "")
    .replace(/[^a-z ]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();

/** Les coordonnées d'un lieu écrit par Liquipedia (« Bucharest », « London, United Kingdom », « France »). */
export function placeOf(location?: string): { lat: number; lon: number; city: boolean } | undefined {
  if (!location) return undefined;
  const parts = location.split(/[,/(]/).map(clean).filter(Boolean);
  for (const p of parts) {
    const c = CITIES[p];
    if (c) return { lat: c[0], lon: c[1], city: true };
  }
  for (const p of parts) {
    const c = COUNTRIES[p];
    if (c) return { lat: c[0], lon: c[1], city: false };
  }
  return undefined;
}
